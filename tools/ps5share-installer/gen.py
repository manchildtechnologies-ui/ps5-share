#!/usr/bin/env python3
# Generates table.c + one llvm-objcopy object per title file for the
# PS5 Share installer payload. Usage: gen.py <dist/PPSA99992> <out-dir>
import os
import re
import subprocess
import sys

SRC, OUT = sys.argv[1], sys.argv[2]
DATA = os.path.join(OUT, "data")
os.makedirs(DATA, exist_ok=True)

OBJCOPY = os.environ.get("LLVM_OBJCOPY", "llvm-objcopy")


def sym_for(rel):
    return "_binary_" + re.sub(r"[^A-Za-z0-9]", "_", rel)


ICON_FIRST = "sce_sys/icon0.png"

all_files = []
for root, _dirs, files in os.walk(SRC):
    for name in files:
        full = os.path.join(root, name)
        rel = os.path.relpath(full, SRC).replace(os.sep, "/")
        all_files.append(rel)
# The app icon embeds first so the installer can write it before the
# first toast references it.
all_files.sort(key=lambda rel: (rel != ICON_FIRST, rel))

entries = []
seen = set()
for rel in all_files:
    obj = os.path.join(DATA, "f%04d.o" % len(entries))
    # Run from inside the title folder so objcopy derives
    # _binary_<relative-path>_start/end/size symbols.
    subprocess.run(
        [OBJCOPY, "--input-target=binary", "--output-target=elf64-x86-64",
         "--binary-architecture=x86-64", rel, obj],
        check=True,
        cwd=SRC,
    )
    sym = sym_for(rel)
    n = 2
    while sym in seen:
        sym = "%s_%d" % (sym_for(rel), n)
        n += 1
    seen.add(sym)
    entries.append((rel, sym, os.path.getsize(os.path.join(SRC, rel))))

with open(os.path.join(OUT, "table.c"), "w") as fh:
    fh.write("/* Generated by tools/ps5share-installer/gen.py; do not edit. */\n")
    fh.write("struct Blob { const char *path; const unsigned char *data;"
             " const unsigned char *end; };\n")
    for _rel, sym, _size in entries:
        fh.write("extern const unsigned char %s_start[];\n" % sym)
        fh.write("extern const unsigned char %s_end[];\n" % sym)
    fh.write("const struct Blob kFiles[] = {\n")
    for rel, sym, _size in entries:
        fh.write('    { "%s", %s_start, %s_end },\n' % (rel, sym, sym))
    fh.write("};\n")
    fh.write("const unsigned long kFileCount = %d;\n" % len(entries))

total = sum(size for _rel, _sym, size in entries)
print("gen: %d files, %d bytes embedded" % (len(entries), total))
